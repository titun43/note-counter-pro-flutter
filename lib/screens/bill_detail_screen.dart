// =============================================================================
// Note Counter Pro - Bill Detail Screen
// =============================================================================
// Shows full bill information with actions:
//   - Mark as Paid / Unpaid toggle
//   - Generate PDF invoice
//   - Share bill summary
//   - Edit bill
//   - Delete bill
// =============================================================================

import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:share_plus/share_plus.dart';
import 'package:url_launcher/url_launcher.dart';
import '../services/storage_service.dart';
import '../services/pdf_service.dart';
import '../models/bill.dart';
import '../utils/constants.dart';
import '../utils/app_localizations.dart';
import 'bill_form_screen.dart';

class BillDetailScreen extends StatefulWidget {
  final String billId;
  /// Optional: pass the Bill object directly to skip the storage lookup
  /// (used when navigating from Customer Detail's bills list).
  final Bill? bill;

  const BillDetailScreen({super.key, required this.billId, this.bill});

  @override
  State<BillDetailScreen> createState() => _BillDetailScreenState();
}

class _BillDetailScreenState extends State<BillDetailScreen> {
  Bill? _bill;
  bool _isGeneratingPdf = false;

  @override
  void initState() {
    super.initState();
    // Use the passed Bill object if available (skip storage lookup).
    if (widget.bill != null) {
      _bill = widget.bill;
    }
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _refresh();
    });
  }

  void _refresh() {
    final bills = context.read<StorageService>().bills;
    final idx = bills.indexWhere((b) => b.id == widget.billId);
    setState(() {
      _bill = idx >= 0 ? bills[idx] : null;
    });
  }

  Future<void> _togglePaid() async {
    if (_bill == null) return;
    final storage = context.read<StorageService>();
    if (_bill!.isPaid) {
      await storage.markBillUnpaid(_bill!.id);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Bill marked as unpaid'),
            backgroundColor: AppColors.warning,
          ),
        );
      }
    } else {
      await storage.markBillPaid(_bill!.id);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('✅ Bill marked as paid'),
            backgroundColor: AppColors.success,
          ),
        );
      }
    }
    _refresh();
  }

  Future<void> _generatePdf() async {
    if (_bill == null) return;
    setState(() => _isGeneratingPdf = true);
    final storage = context.read<StorageService>();
    await PdfService.generateBillPdf(_bill!, storage);
    if (mounted) setState(() => _isGeneratingPdf = false);
  }

  Future<void> _shareBill() async {
    if (_bill == null) return;
    final symbol = AppConstants.getCurrencySymbol(_bill!.currency);
    final status = _bill!.isPaid
        ? 'PAID'
        : (_bill!.status == 'overdue' ? 'OVERDUE' : 'UNPAID');
    final dueStr = _bill!.dueDate != null
        ? '\nDue: ${_bill!.dueDate!.day}/${_bill!.dueDate!.month}/${_bill!.dueDate!.year}'
        : '';
    final itemsStr = _bill!.items.asMap().entries.map((e) {
      final i = e.key + 1;
      final item = e.value;
      return '$i. ${item.name} × ${item.quantity} — $symbol${item.total.toStringAsFixed(2)}';
    }).join('\n');
    final msg = '''
🧾 *INVOICE ${_bill!.billNumber}*

👤 Customer: ${_bill!.customerName ?? 'Walk-in Customer'}
📅 Date: ${_bill!.date.day}/${_bill!.date.month}/${_bill!.date.year}$dueStr
Status: $status

──────────────
$itemsStr
──────────────

Subtotal: $symbol${_bill!.subtotal.toStringAsFixed(2)}
${_bill!.totalGst > 0 ? 'GST: $symbol${_bill!.totalGst.toStringAsFixed(2)}\n' : ''}${_bill!.discountPercent > 0 ? 'Discount: -$symbol${_bill!.discountAmount.toStringAsFixed(2)}\n' : ''}
*TOTAL: $symbol${_bill!.total.toStringAsFixed(2)}*

${_bill!.notes != null && _bill!.notes!.isNotEmpty ? 'Notes: ${_bill!.notes}\n' : ''}— Generated by Note Counter Pro
''';
    await Share.share(msg, subject: 'Invoice ${_bill!.billNumber}');
  }

  Future<void> _callCustomer() async {
    if (_bill?.customerPhone == null || _bill!.customerPhone!.isEmpty) return;
    final uri = Uri.parse('tel:${_bill!.customerPhone}');
    if (await canLaunchUrl(uri)) await launchUrl(uri);
  }

  Future<void> _editBill() async {
    if (_bill == null) return;
    final result = await Navigator.push<bool>(
      context,
      MaterialPageRoute(
        builder: (_) => BillFormScreen(existingBill: _bill),
      ),
    );
    if (result == true) _refresh();
  }

  /// Record an additional payment against this bill (#11).
  /// Opens a dialog where the user enters how much more the customer
  /// has paid. The amount is added to bill.paidAmount, and the linked
  /// Khata entry is synced (so the customer's debit balance decreases).
  Future<void> _recordPayment() async {
    if (_bill == null) return;
    final loc = context.loc;
    final amountController = TextEditingController();
    final remaining = _bill!.remainingAmount;

    final result = await showDialog<double>(
      context: context,
      builder: (ctx) {
        return AlertDialog(
          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
          title: Row(
            children: [
              const Icon(Icons.payments, color: Color(0xFFD4AF37), size: 24),
              const SizedBox(width: 8),
              Expanded(
                child: Text(
                  loc.t('recordPayment'),
                  style: const TextStyle(fontSize: 16, fontWeight: FontWeight.bold),
                ),
              ),
            ],
          ),
          content: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(
                '${loc.t('total')}: $symbol${_bill!.total.toStringAsFixed(2)}',
                style: const TextStyle(fontSize: 13),
              ),
              Text(
                '${loc.t('amountPaid')}: $symbol${_bill!.paidAmount.toStringAsFixed(2)}',
                style: const TextStyle(fontSize: 13),
              ),
              Text(
                '${loc.t('remaining')}: $symbol${remaining.toStringAsFixed(2)}',
                style: TextStyle(
                  fontSize: 14,
                  fontWeight: FontWeight.bold,
                  color: remaining > 0 ? AppColors.warning : AppColors.success,
                ),
              ),
              const SizedBox(height: 12),
              TextField(
                controller: amountController,
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                decoration: InputDecoration(
                  labelText: loc.t('paymentAmount'),
                  prefixText: '$symbol ',
                  border: const OutlineInputBorder(),
                  isDense: true,
                ),
                autofocus: true,
              ),
            ],
          ),
          actionsPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(ctx, -1),
              child: Text(loc.t('cancel')),
            ),
            FilledButton(
              style: FilledButton.styleFrom(
                backgroundColor: const Color(0xFFD4AF37),
                foregroundColor: Colors.white,
              ),
              onPressed: () {
                final amt = double.tryParse(amountController.text.trim()) ?? 0;
                Navigator.pop(ctx, amt);
              },
              child: Text(loc.t('save')),
            ),
          ],
        );
      },
    );

    if (result == null || result < 0) return; // cancelled
    if (result <= 0) return; // invalid amount

    final storage = context.read<StorageService>();
    final newPaidAmount = _bill!.paidAmount + result;
    final oldRemaining = _bill!.remainingAmount;

    // Update the bill with the new paid amount.
    final updated = _bill!.copyWith(
      paidAmount: newPaidAmount,
      isPaid: newPaidAmount >= _bill!.total,
      paidAt: newPaidAmount >= _bill!.total
          ? (_bill!.paidAt ?? DateTime.now())
          : null,
    );
    await storage.updateBill(updated);

    // Sync the linked Khata entry (so the customer's debit balance
    // decreases by the payment amount).
    await storage.syncLinkedKhataEntry(updated);

    // Adjust the customer's totalDebit down by the payment amount
    // (but not below 0).
    if (updated.customerId != null && updated.customerId!.isNotEmpty) {
      final debitDelta = -result.clamp(0, oldRemaining).toDouble();
      if (debitDelta.abs() > 0.01) {
        await storage.adjustCustomerDebit(updated.customerId!, debitDelta);
      }
    }

    _refresh();
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('${loc.t('paymentRecorded')}: $symbol${result.toStringAsFixed(2)}'),
          backgroundColor: AppColors.success,
        ),
      );
    }
  }

  Future<void> _deleteBill() async {
    if (_bill == null) return;
    final loc = context.loc;
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Row(
          children: [
            Icon(Icons.delete, color: AppColors.danger),
            const SizedBox(width: 8),
            Text(loc.t('delete')),
          ],
        ),
        content: Text(
            'Delete ${_bill!.billNumber}? ${loc.t('cannotBeUndone')}'),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            child: Text(loc.t('cancel')),
          ),
          FilledButton(
            style: FilledButton.styleFrom(backgroundColor: AppColors.danger),
            onPressed: () => Navigator.pop(ctx, true),
            child: Text(loc.t('delete')),
          ),
        ],
      ),
    );
    if (confirmed == true) {
      await context.read<StorageService>().deleteBill(_bill!.id);
      if (mounted) Navigator.pop(context, true);
    }
  }

  @override
  Widget build(BuildContext context) {
    final loc = context.loc;
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    if (_bill == null) {
      return Scaffold(
        appBar: AppBar(title: Text(loc.t('billDetails'))),
        body: const Center(child: CircularProgressIndicator()),
      );
    }

    final bill = _bill!;
    final symbol = AppConstants.getCurrencySymbol(bill.currency);

    Color statusColor;
    String statusLabel;
    switch (bill.status) {
      case 'paid':
        statusColor = AppColors.success;
        statusLabel = loc.t('paid');
        break;
      case 'overdue':
        statusColor = AppColors.danger;
        statusLabel = loc.t('overdue');
        break;
      default:
        statusColor = AppColors.warning;
        statusLabel = loc.t('unpaid');
    }

    return Scaffold(
      appBar: AppBar(
        title: Text(
          bill.billNumber,
          style: const TextStyle(fontFamily: 'KhataHandwriting', fontSize: 22),
        ),
        actions: [
          PopupMenuButton<String>(
            icon: const Icon(Icons.more_vert),
            onSelected: (v) {
              switch (v) {
                case 'edit':
                  _editBill();
                  break;
                case 'delete':
                  _deleteBill();
                  break;
              }
            },
            itemBuilder: (ctx) => [
              PopupMenuItem(
                value: 'edit',
                child: Row(children: [
                  const Icon(Icons.edit, size: 20, color: AppColors.info),
                  const SizedBox(width: 12),
                  Text(loc.t('edit')),
                ]),
              ),
              PopupMenuItem(
                value: 'delete',
                child: Row(children: [
                  const Icon(Icons.delete, size: 20, color: AppColors.danger),
                  const SizedBox(width: 12),
                  Text(loc.t('delete')),
                ]),
              ),
            ],
          ),
        ],
      ),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          // === Status banner ===
          Container(
            margin: const EdgeInsets.only(bottom: 12),
            padding: const EdgeInsets.all(14),
            decoration: BoxDecoration(
              color: statusColor.withOpacity(0.12),
              borderRadius: BorderRadius.circular(12),
              border: Border.all(color: statusColor, width: 1),
            ),
            child: Row(
              children: [
                Icon(bill.isPaid ? Icons.check_circle : Icons.pending,
                    color: statusColor, size: 32),
                const SizedBox(width: 12),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(statusLabel,
                          style: TextStyle(
                              color: statusColor,
                              fontWeight: FontWeight.bold,
                              fontSize: 16)),
                      if (bill.isPaid && bill.paidAt != null)
                        Text(
                            'Paid on ${bill.paidAt!.day}/${bill.paidAt!.month}/${bill.paidAt!.year}',
                            style: const TextStyle(
                                fontSize: 11, color: AppColors.textSecondary)),
                      if (!bill.isPaid && bill.dueDate != null)
                        Text(
                            'Due: ${bill.dueDate!.day}/${bill.dueDate!.month}/${bill.dueDate!.year}',
                            style: const TextStyle(
                                fontSize: 11, color: AppColors.textSecondary)),
                    ],
                  ),
                ),
                TextButton(
                  onPressed: _togglePaid,
                  style: TextButton.styleFrom(foregroundColor: statusColor),
                  child: Text(bill.isPaid
                      ? (loc.t('markUnpaid'))
                      : (loc.t('markPaid'))),
                ),
              ],
            ),
          ),

          // === Customer info card ===
          _card(isDark, [
            ListTile(
              leading: CircleAvatar(
                backgroundColor: AppColors.primary,
                child: Text(
                  (bill.customerName != null && bill.customerName!.isNotEmpty)
                      ? bill.customerName![0].toUpperCase()
                      : '?',
                  style: const TextStyle(color: Colors.white),
                ),
              ),
              title: Text(
                bill.customerName ?? 'Walk-in Customer',
                style: const TextStyle(fontWeight: FontWeight.bold),
              ),
              subtitle: bill.customerPhone != null &&
                      bill.customerPhone!.isNotEmpty
                  ? Text(bill.customerPhone!)
                  : Text(loc.t('noPhoneCustomer'),
                      style: const TextStyle(fontStyle: FontStyle.italic)),
              trailing: bill.customerPhone != null &&
                      bill.customerPhone!.isNotEmpty
                  ? IconButton(
                      icon: const Icon(Icons.call, color: AppColors.info),
                      onPressed: _callCustomer,
                    )
                  : null,
            ),
          ]),

          // === Bill info ===
          _card(isDark, [
            ListTile(
              leading:
                  const Icon(Icons.receipt, color: AppColors.primary),
              title: Text(loc.t('billNumber')),
              trailing: Text(bill.billNumber,
                  style: const TextStyle(fontWeight: FontWeight.bold)),
            ),
            const Divider(height: 1, indent: 16),
            ListTile(
              leading: const Icon(Icons.event, color: AppColors.info),
              title: Text(loc.t('date')),
              trailing: Text(
                  '${bill.date.day}/${bill.date.month}/${bill.date.year}'),
            ),
            if (bill.dueDate != null) ...[
              const Divider(height: 1, indent: 16),
              ListTile(
                leading: Icon(Icons.event_busy,
                    color: bill.status == 'overdue'
                        ? AppColors.danger
                        : AppColors.warning),
                title: Text(loc.t('dueDate')),
                trailing: Text(
                    '${bill.dueDate!.day}/${bill.dueDate!.month}/${bill.dueDate!.year}',
                    style: TextStyle(
                        color: bill.status == 'overdue'
                            ? AppColors.danger
                            : null,
                        fontWeight: bill.status == 'overdue'
                            ? FontWeight.bold
                            : null)),
              ),
            ],
          ]),

          // === Items ===
          _card(isDark, [
            Padding(
              padding: const EdgeInsets.fromLTRB(16, 12, 16, 4),
              child: Text(
                loc.t('items'),
                style: const TextStyle(
                    fontWeight: FontWeight.bold,
                    fontFamily: 'KhataHandwriting',
                    fontSize: 16),
              ),
            ),
            const Divider(height: 1),
            ...bill.items.asMap().entries.map((entry) {
              final i = entry.key + 1;
              final item = entry.value;
              return ListTile(
                leading: CircleAvatar(
                  backgroundColor: AppColors.primary.withOpacity(0.15),
                  child: Text('$i',
                      style: const TextStyle(color: AppColors.primaryDark)),
                ),
                title: Text(item.name,
                    style: const TextStyle(fontWeight: FontWeight.w600)),
                subtitle: Text(
                    '${item.quantity} × $symbol${item.price.toStringAsFixed(2)}'
                    '${item.gstPercent != null ? ' (GST ${item.gstPercent!.toStringAsFixed(0)}%)' : ''}'),
                trailing: Text(
                  '$symbol${item.total.toStringAsFixed(2)}',
                  style: const TextStyle(fontWeight: FontWeight.bold),
                ),
              );
            }),
          ]),

          // === Totals ===
          Container(
            margin: const EdgeInsets.symmetric(vertical: 12),
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              gradient: LinearGradient(
                colors: isDark
                    ? [const Color(0xFF16213E), const Color(0xFF1A1A2E)]
                    : [const Color(0xFFFFF8DC), Colors.white],
                begin: Alignment.topLeft,
                end: Alignment.bottomRight,
              ),
              borderRadius: BorderRadius.circular(12),
              border: Border.all(
                  color: const Color(0xFFD4AF37).withOpacity(0.3), width: 1),
            ),
            child: Column(
              children: [
                _totalRow('Subtotal', '$symbol${bill.subtotal.toStringAsFixed(2)}'),
                if (bill.totalGst > 0)
                  _totalRow('GST', '$symbol${bill.totalGst.toStringAsFixed(2)}'),
                if (bill.discountPercent > 0)
                  _totalRow(
                      'Discount (${bill.discountPercent.toStringAsFixed(0)}%)',
                      '-$symbol${bill.discountAmount.toStringAsFixed(2)}'),
                const Divider(height: 16),
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Text(loc.t('total'),
                        style: const TextStyle(
                            fontWeight: FontWeight.bold, fontSize: 16)),
                    Text('$symbol${bill.total.toStringAsFixed(2)}',
                        style: TextStyle(
                            fontWeight: FontWeight.bold,
                            fontSize: 22,
                            color: AppColors.danger)),
                  ],
                ),
              ],
            ),
          ),

          // === Notes ===
          if (bill.notes != null && bill.notes!.isNotEmpty)
            _card(isDark, [
              Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(children: [
                      const Icon(Icons.note, color: AppColors.textSecondary, size: 18),
                      const SizedBox(width: 8),
                      Text(loc.t('notes'),
                          style: const TextStyle(fontWeight: FontWeight.bold)),
                    ]),
                    const SizedBox(height: 6),
                    Text(bill.notes!,
                        style: const TextStyle(color: AppColors.textSecondary)),
                  ],
                ),
              ),
            ]),

          const SizedBox(height: 16),
          // === Record Payment button (#11) — only show if not fully paid ===
          if (!_bill!.isPaid && _bill!.remainingAmount > 0)
            Container(
              margin: const EdgeInsets.only(bottom: 8),
              width: double.infinity,
              child: FilledButton.icon(
                onPressed: _recordPayment,
                icon: const Icon(Icons.payments, size: 18),
                label: Text(loc.t('recordPayment')),
                style: FilledButton.styleFrom(
                  backgroundColor: const Color(0xFFD4AF37),
                  foregroundColor: const Color(0xFF1A1A2E),
                  padding: const EdgeInsets.symmetric(vertical: 14),
                ),
              ),
            ),
          // === Action buttons ===
          Row(
            children: [
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: _isGeneratingPdf ? null : _generatePdf,
                  icon: _isGeneratingPdf
                      ? const SizedBox(
                          width: 16,
                          height: 16,
                          child: CircularProgressIndicator(strokeWidth: 2),
                        )
                      : const Icon(Icons.picture_as_pdf),
                  label: Text(loc.t('pdf')),
                  style: OutlinedButton.styleFrom(foregroundColor: AppColors.danger),
                ),
              ),
              const SizedBox(width: 8),
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: _shareBill,
                  icon: const Icon(Icons.share),
                  label: Text(loc.t('share')),
                  style: OutlinedButton.styleFrom(foregroundColor: AppColors.info),
                ),
              ),
            ],
          ),
          const SizedBox(height: 8),
          Row(
            children: [
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: _editBill,
                  icon: const Icon(Icons.edit),
                  label: Text(loc.t('edit')),
                  style: OutlinedButton.styleFrom(foregroundColor: AppColors.info),
                ),
              ),
              const SizedBox(width: 8),
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: _deleteBill,
                  icon: const Icon(Icons.delete_outline),
                  label: Text(loc.t('delete')),
                  style: OutlinedButton.styleFrom(foregroundColor: AppColors.danger),
                ),
              ),
            ],
          ),
          const SizedBox(height: 24),
        ],
      ),
    );
  }

  Widget _card(bool isDark, List<Widget> children) {
    return Container(
      margin: const EdgeInsets.symmetric(vertical: 6),
      decoration: BoxDecoration(
        color: isDark ? const Color(0xFF16213E) : Colors.white,
        borderRadius: BorderRadius.circular(12),
        border: Border.all(
            color: const Color(0xFFD4AF37).withOpacity(0.2), width: 1),
        boxShadow: [
          BoxShadow(
            color: isDark
                ? Colors.black.withOpacity(0.2)
                : Colors.black.withOpacity(0.04),
            blurRadius: 4,
            offset: const Offset(0, 2),
          ),
        ],
      ),
      child: Column(children: children),
    );
  }

  Widget _totalRow(String label, String value) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 2),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(label, style: const TextStyle(color: AppColors.textSecondary)),
          Text(value, style: const TextStyle(fontWeight: FontWeight.bold)),
        ],
      ),
    );
  }
}
